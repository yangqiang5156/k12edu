export function scienceLesson(title: string, method = ''): ScienceLesson {
  const [result, explanation] = findings[title] ?? [
    '按照方法完成后，会看到、听到或测到可以比较的变化；请把实际观察到的现象记下来。',
    '观察时要尽量只改变一个条件，保持其他条件相同，并重复一次；这样才能用过程解释结果。'
  ];
  return {
    question: title,
    method: method.trim() || '请在家长陪伴下，先猜想，再按步骤观察并记录。',
    result,
    explanation
  };
}

export function scienceSpeechText(lesson: ScienceLesson): string {
  return `科学问题，${lesson.question}。观察方法，${lesson.method}。观察结果，${lesson.result}。科学解释，${lesson.explanation}`;
}
